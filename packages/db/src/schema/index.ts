export const stockItems = pgTable(
  "stock_items",
  {
    id: idPk(),
    user_id: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    ingredient_id: uuid("ingredient_id")
      .notNull()
      .references(() => ingredients.id, { onDelete: "restrict" }),
    location_id: uuid("location_id")
      .notNull()
      .references(() => locations.id, { onDelete: "restrict" }),
    quantity: numeric("quantity", { precision: 12, scale: 3 }).notNull(),
    unit: storageUnitEnum("unit").notNull(),
    original_quantity: numeric("original_quantity", { precision: 12, scale: 3 }),
    barcode: text("barcode").references(() => barcodes.gtin, { onDelete: "set null" }),
    purchased_at: date("purchased_at"),
    expiry_date: date("expiry_date"),
    opened_at: timestamp("opened_at", { withTimezone: true }),
    notes: text("notes"),
    confidence: numeric("confidence", { precision: 4, scale: 3 }).notNull().default("1.000"),
    source: stockSourceEnum("source").notNull(),
    source_event_id: uuid("source_event_id"),
    created_at: createdAt(),
    updated_at: updatedAt(),
    deleted_at: deletedAt(),
  },
  (t) => [
    index("stock_items_user_ingredient_location_idx").on(t.user_id, t.ingredient_id, t.location_id),
    index("stock_items_user_expiry_idx").on(t.user_id, t.expiry_date),
    index("stock_items_source_event_idx").on(t.source_event_id),
  ],
);

