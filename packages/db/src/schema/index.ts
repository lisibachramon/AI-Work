// ---------- Ingredients ----------

export const ingredients = pgTable(
  "ingredients",
  {
    id: idPk(),
    user_id: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    canonical_name_de: text("canonical_name_de").notNull(),
    canonical_name_en: text("canonical_name_en"),
    category: ingredientCategoryEnum("category").notNull(),
    default_unit: storageUnitEnum("default_unit").notNull(),
    density_g_per_ml: numeric("density_g_per_ml", { precision: 8, scale: 4 }),
    typical_piece_weight_g: numeric("typical_piece_weight_g", { precision: 10, scale: 2 }),
    shelf_life_days: integer("shelf_life_days"),
    embedding: vector(1024)("embedding"),
    // tsvector generated by trigger using german_unaccent config (see migration).
    name_tsv: tsvector("name_tsv"),
    created_at: createdAt(),
    updated_at: updatedAt(),
  },
  (t) => [
    index("ingredients_user_id_idx").on(t.user_id),
    uniqueIndex("ingredients_user_canonical_idx").on(t.user_id, t.canonical_name_de),
    // GIN on name_tsv and HNSW on embedding declared in raw SQL migration.
  ],
);

export const ingredientAliases = pgTable(
  "ingredient_aliases",
  {
    id: idPk(),
    ingredient_id: uuid("ingredient_id")
      .notNull()
      .references(() => ingredients.id, { onDelete: "cascade" }),
    alias: text("alias").notNull(),
    lang: text("lang").notNull().default("de-CH"),
    source: text("source").notNull().default("user"),
    confidence: numeric("confidence", { precision: 4, scale: 3 }).notNull().default("1.000"),
    created_at: createdAt(),
  },
  (t) => [
    uniqueIndex("ingredient_aliases_unique_idx").on(t.ingredient_id, t.alias, t.lang),
    index("ingredient_aliases_alias_idx").on(t.alias),
    // pg_trgm GIN index declared in raw SQL migration.
  ],
);

